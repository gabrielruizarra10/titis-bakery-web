import assert from 'node:assert/strict';
import {localDateKey,validateOrder,buildMessage} from '../order-utils.js';
const order={name:'Ana López',phone:'+503 7877 0000',date:'2026-12-12',occasion:'Cumpleaños',portions:'12',flavor:'Chocolate',design:'Flores & tonos rosa',diet:'Consultar por almendras'};
assert.deepEqual(validateOrder(order,'2026-11-11'),{});
assert.ok(validateOrder({...order,date:'2026-02-31'},'2026-01-01').date);
assert.ok(validateOrder({...order,date:'2026-11-10'},'2026-11-11').date);
assert.ok(validateOrder({...order,phone:'123'},'2026-11-11').phone);
assert.ok(validateOrder({...order,portions:'1.5'},'2026-11-11').portions);
assert.ok(validateOrder({...order,portions:'0'},'2026-11-11').portions);
assert.equal(Object.keys(validateOrder({},'2026-11-11')).length,5);
assert.equal(localDateKey(new Date(2026,10,11,23,59)),'2026-11-11');
const message=buildMessage(order,'pastel.png');
assert.ok(message.includes('12/12/2026'));
assert.ok(message.includes('Flores & tonos rosa'));
assert.ok(message.includes('adjuntaré pastel.png'));
assert.ok(message.includes('no confirma ni reserva'));
assert.equal(decodeURIComponent(encodeURIComponent(message)),message);
assert.ok(!buildMessage(order).includes('Foto de inspiración:'));
console.log('Order validation, date handling and WhatsApp encoding checks passed.');
